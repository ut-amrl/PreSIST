#!/usr/bin/env python3
"""
Split files/directories from a manifest into one or more zip files.

Input:
  A text file where each non-empty, non-comment line is a file or directory path.

Behavior:
  - Files are added directly.
  - Directories are walked recursively.
  - One or more zip files are created, each capped at a maximum uncompressed size.
  - Paths inside the zip are stored relative to --arc-root (defaults to the
    manifest file's parent directory).

Copying data to another machine at the same absolute paths
----------------------------------------------------------
If your manifest was generated by build_manifest.py (paths are relative to
dataset_root) and you want files to land at the same absolute location on the
destination, set both --base-dir and --arc-root to dataset_root:

  python zip_manifest.py manifest.txt /transfer/archive \\
      --base-dir /workspace/data/input \\
      --arc-root /workspace/data/input

On the destination machine, extract each part to the same base path:

  for f in /transfer/archive.part*.zip; do
      unzip "$f" -d /workspace/data/input/
  done

The zip files themselves can be placed anywhere on the destination; only the
extraction directory matters.

Example:
  python zip_manifest.py manifest.txt output/archive --max-size 700M
"""

from __future__ import annotations

import argparse
import os
import sys
import zipfile
from pathlib import Path
from typing import Iterable, List, Tuple


def parse_size(size_str: str) -> int:
    """
    Parse a human-readable size like:
      500K, 100M, 2G, 1048576
    Returns bytes.
    """
    s = size_str.strip().upper()
    units = {
        "K": 1024,
        "M": 1024 ** 2,
        "G": 1024 ** 3,
        "T": 1024 ** 4,
    }

    if s.isdigit():
        return int(s)

    if len(s) < 2:
        raise ValueError(f"Invalid size: {size_str}")

    suffix = s[-1]
    number = s[:-1]

    if suffix not in units:
        raise ValueError(
            f"Invalid size suffix in '{size_str}'. Use bytes or K/M/G/T."
        )

    try:
        value = float(number)
    except ValueError as exc:
        raise ValueError(f"Invalid size number in '{size_str}'") from exc

    return int(value * units[suffix])


def read_manifest(manifest_path: Path, base_dir: Path | None = None) -> List[Path]:
    """
    Read manifest lines. Ignores:
      - blank lines
      - lines starting with '#'
    Resolves relative paths against base_dir (defaults to the manifest file's
    parent directory). Pass an explicit base_dir to decouple the manifest
    location from the dataset root.
    """
    if base_dir is None:
        base_dir = manifest_path.parent.resolve()
    else:
        base_dir = base_dir.resolve()
    results: List[Path] = []

    with manifest_path.open("r", encoding="utf-8") as f:
        for line_num, raw_line in enumerate(f, start=1):
            line = raw_line.strip()

            if not line or line.startswith("#"):
                continue

            p = Path(line)
            if not p.is_absolute():
                p = base_dir / p

            results.append(p.resolve())

    return results


def collect_files(paths: Iterable[Path]) -> List[Path]:
    """
    Expand files/directories into a flat list of files.
    """
    files: List[Path] = []
    seen = set()

    for path in paths:
        if not path.exists():
            print(f"WARNING: Path does not exist, skipping: {path}", file=sys.stderr)
            continue

        if path.is_file():
            rp = str(path.resolve())
            if rp not in seen:
                files.append(path.resolve())
                seen.add(rp)
            continue

        if path.is_dir():
            for root, _, filenames in os.walk(path):
                root_path = Path(root)
                for name in filenames:
                    file_path = (root_path / name).resolve()
                    rp = str(file_path)
                    if rp not in seen:
                        files.append(file_path)
                        seen.add(rp)
            continue

        print(f"WARNING: Not a regular file or directory, skipping: {path}", file=sys.stderr)

    return sorted(files)


def safe_arcname(file_path: Path, root_base: Path) -> str:
    """
    Build archive path relative to root_base when possible.
    Falls back to filename if not relative.
    """
    try:
        return str(file_path.relative_to(root_base))
    except ValueError:
        # If file is outside the chosen base, store a normalized version
        drive = file_path.drive.replace(":", "") if file_path.drive else ""
        parts = [part for part in file_path.parts if part not in (file_path.anchor, file_path.drive)]
        if drive:
            return str(Path(drive, *parts))
        return str(Path(*parts))


def chunk_files(
    files: List[Path],
    max_size_bytes: int,
) -> List[List[Tuple[Path, int]]]:
    """
    Group files into chunks whose total source file size is <= max_size_bytes.
    Note:
      This uses original file sizes, not final compressed zip size.
      Actual zip size may be smaller or slightly larger.
    """
    chunks: List[List[Tuple[Path, int]]] = []
    current_chunk: List[Tuple[Path, int]] = []
    current_size = 0

    for file_path in files:
        file_size = file_path.stat().st_size

        if file_size > max_size_bytes:
            if current_chunk:
                chunks.append(current_chunk)
                current_chunk = []
                current_size = 0
            chunks.append([(file_path, file_size)])
            continue

        if current_size + file_size > max_size_bytes and current_chunk:
            chunks.append(current_chunk)
            current_chunk = [(file_path, file_size)]
            current_size = file_size
        else:
            current_chunk.append((file_path, file_size))
            current_size += file_size

    if current_chunk:
        chunks.append(current_chunk)

    return chunks


def create_zip_archives(
    chunks: List[List[Tuple[Path, int]]],
    output_base: Path,
    arc_root: Path,
    compression: int,
) -> None:
    """
    Write one zip file per chunk.
    """
    output_base.parent.mkdir(parents=True, exist_ok=True)

    for index, chunk in enumerate(chunks, start=1):
        zip_path = output_base.with_name(f"{output_base.name}.part{index:03d}.zip")

        print(f"Creating: {zip_path}")
        with zipfile.ZipFile(zip_path, "w", compression=compression, allowZip64=True) as zf:
            for file_path, file_size in chunk:
                arcname = safe_arcname(file_path, arc_root)
                print(f"  adding: {file_path} -> {arcname} ({file_size} bytes)")
                zf.write(file_path, arcname=arcname)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Create one or more zip files from a manifest of files/directories."
    )
    parser.add_argument(
        "manifest",
        type=Path,
        help="Path to text file listing files/directories, one per line.",
    )
    parser.add_argument(
        "output_base",
        type=Path,
        help=(
            "Base name/path for the generated zip files.\n\n"
            "Example:\n"
            "  output_base = ./backup/archive\n"
            "Produces:\n"
            "  ./backup/archive.part001.zip\n"
            "  ./backup/archive.part002.zip\n"
            "  ...\n\n"
            "The final '.zip' extension and part number are added automatically."
        ),
    )
    parser.add_argument(
        "--base-dir",
        type=Path,
        default=None,
        help=(
            "Base directory used to resolve relative paths in the manifest.\n\n"
            "Default: the directory containing the manifest file.\n\n"
            "Set this to your dataset_root when the manifest was generated by\n"
            "build_manifest.py and lives outside the dataset directory."
        ),
    )

    parser.add_argument(
        "--store",
        action="store_true",
        help="Store files without compression.",
    )



    parser.add_argument(
        "--max-size",
        default="10G",
        help=(
            "Maximum size per generated zip part.\n"
            "Default: 10G\n\n"
            "Examples:\n"
            "  --max-size 500M\n"
            "  --max-size 2G\n"
            "  --max-size 1048576"
        ),
    )

    parser.add_argument(
        "--arc-root",
        type=Path,
        default=None,
        help=(
            "Base directory used to determine the path stored inside the zip.\n\n"
            "Default: the directory containing the manifest file.\n\n"
            "Example:\n"
            "  Manifest file is in: /data\n"
            "  File being added:    /data/photos/2025/img1.jpg\n\n"
            "With default arc-root (/data), the file appears in the zip as:\n"
            "  photos/2025/img1.jpg\n\n"
            "If you instead use:\n"
            "  --arc-root /data/photos\n\n"
            "then the same file appears in the zip as:\n"
            "  2025/img1.jpg\n\n"
            "This only affects the names inside the zip; it does not affect which\n"
            "files are included."
        ),
    )

    args = parser.parse_args()

    manifest_path = args.manifest.resolve()
    if not manifest_path.is_file():
        print(f"ERROR: Manifest file not found: {manifest_path}", file=sys.stderr)
        return 1

    try:
        max_size_bytes = parse_size(args.max_size)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if max_size_bytes <= 0:
        print("ERROR: --max-size must be greater than 0", file=sys.stderr)
        return 1

    compression = zipfile.ZIP_STORED if args.store else zipfile.ZIP_DEFLATED
    base_dir = args.base_dir.resolve() if args.base_dir is not None else None
    manifest_entries = read_manifest(manifest_path, base_dir=base_dir)
    files = collect_files(manifest_entries)

    if not files:
        print("ERROR: No valid files found from manifest.", file=sys.stderr)
        return 1

    arc_root = (
        args.arc_root.resolve()
        if args.arc_root is not None
        else manifest_path.parent.resolve()
    )

    chunks = chunk_files(files, max_size_bytes)

    print(f"Found {len(files)} file(s).")
    print(f"Creating {len(chunks)} zip file(s).")
    create_zip_archives(chunks, args.output_base.resolve(), arc_root, compression)

    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())