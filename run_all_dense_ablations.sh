#!/usr/bin/env bash
# Dense persistence predictor — variant sweep.
#
# Distributes the five dense-predictor variants from the plan across the
# given GPUs using run_ablations.py (one config per GPU at a time; queue
# drains as slots free up).
#
# Order matches the plan's "recommended training order":
#   A4 -> A5 -> C1 -> C4 -> C3
# Earlier entries dispatch first, so on 4 GPUs you'll get
# A4/A5/C1/C4 launched in parallel and C3 takes the first free slot.
#
# Usage:
#   ./run_all_dense_ablations.sh                              # default GPUs 0,1,2,3
#   ./run_all_dense_ablations.sh 0,1,2,3                      # explicit GPUs
#   ./run_all_dense_ablations.sh 0,1,2,3 --force              # re-run completed
#   ./run_all_dense_ablations.sh 0,1,2,3 --on-busy poll       # wait for busy GPUs
#   ./run_all_dense_ablations.sh 0,1,2,3 -- +train_dataset.train_subsample_fraction=0.02 \
#                                           +train_dataset.val_subsample_fraction=0.1
#                                                             # smoke run across all
#
# Anything after the GPU list is forwarded to run_ablations.py.
#
# C3 (..._invfreq) needs a precomputed label-inverse-frequency table at
# $INVFREQ_TABLE_PATH below. If the file is missing, this script runs
# scripts/compute_label_inverse_freq.py once before dispatching, using
# the A4 config so bins are in the same z-score space C3 trains in. Set
# SKIP_INVFREQ_PRECOMPUTE=1 to skip (e.g. if you regenerated by hand).

set -euo pipefail

GPUS="${1:-0,1,2,3}"
shift || true

LOG_DIR="${LOG_DIR:-ablation_logs}"

# Reduce fragmentation OOMs on memory-tight GPUs.
export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"

DENSE_PREFIX=dpt_dense_seg_langSam3Q8T_behav4_mO20_imgbal

A4="${DENSE_PREFIX}_lowlr_huber_norm_loose50"
A5="${DENSE_PREFIX}_lowlr_huber_norm_loose50_noaux"
C1="${DENSE_PREFIX}_aux_areawavg"
C4="${DENSE_PREFIX}_lowlr_huber_norm_loose50_negconf"
C3="${DENSE_PREFIX}_lowlr_huber_norm_loose50_invfreq"

CONFIGS=(
  "$A4"
  "$A5"
  "$C1"
  "$C4"
  "$C3"
)

# --- C3 precompute (freq table) ------------------------------------------
# Path must match what the dataset config seg_..._dense_norm_invfreq.yaml
# references. Keep in sync if you change either side.
INVFREQ_TABLE_PATH="${INVFREQ_TABLE_PATH:-/workspace/data/output/dense_supervision_cache/label_invfreq_y50_post_norm.npz}"

if [[ "${SKIP_INVFREQ_PRECOMPUTE:-0}" != "1" ]]; then
  if [[ ! -f "$INVFREQ_TABLE_PATH" ]]; then
    echo "[precompute] freq table missing at $INVFREQ_TABLE_PATH"
    echo "[precompute] running scripts/compute_label_inverse_freq.py (CPU-only) ..."
    # CPU-only so it doesn't fight a training run for GPU memory.
    CUDA_VISIBLE_DEVICES= python scripts/compute_label_inverse_freq.py \
      --config-name="$A4" \
      --out-npz "$INVFREQ_TABLE_PATH"
  else
    echo "[precompute] freq table already present at $INVFREQ_TABLE_PATH"
  fi
fi

exec python run_ablations.py \
  --gpus "$GPUS" \
  --log-dir "$LOG_DIR" \
  --configs "${CONFIGS[@]}" \
  "$@"
